const LANG_KEY = 'onsofa-lang';
const LANGS = [
  { code: 'en', label: 'EN', flag: '🇬🇧', name: 'English'  },
  { code: 'fa', label: 'FA', flag: '🇮🇷', name: 'فارسی'    },
  { code: 'es', label: 'ES', flag: '🇪🇸', name: 'Español'  },
  { code: 'ko', label: 'KO', flag: '🇰🇷', name: '한국어'    },
  { code: 'fr', label: 'FR', flag: '🇫🇷', name: 'Français' },
  { code: 'tr', label: 'TR', flag: '🇹🇷', name: 'Türkçe'   },
  { code: 'ar', label: 'AR', flag: '🇸🇦', name: 'العربية'  },
];
const RTL_LANGS = ['fa', 'ar'];

function getLang() {
  return localStorage.getItem(LANG_KEY) || 'en';
}

function applyLang(lang) {
  const t = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  localStorage.setItem(LANG_KEY, lang);

  // RTL
  document.documentElement.setAttribute('dir', RTL_LANGS.includes(lang) ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lang);

  // Translate all tagged elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  // Update trigger pill to show active language
  const active = LANGS.find(l => l.code === lang) || LANGS[0];
  document.querySelectorAll('.lang-trigger').forEach(trigger => {
    trigger.querySelector('.lang-flag').textContent = active.flag;
    trigger.querySelector('.lang-code').textContent = active.label;
  });

  // Mark active option in dropdown
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Close all dropdowns
  document.querySelectorAll('.lang-switcher').forEach(sw => sw.classList.remove('open'));
}

function buildLangSwitcher() {
  document.querySelectorAll('.lang-switcher').forEach(container => {
    const currentLang = getLang();
    const active = LANGS.find(l => l.code === currentLang) || LANGS[0];

    // Build trigger button
    const trigger = document.createElement('button');
    trigger.className = 'lang-trigger';
    trigger.setAttribute('aria-haspopup', 'listbox');
    trigger.setAttribute('aria-label', 'Select language');
    trigger.innerHTML = `
      <span class="lang-flag">${active.flag}</span>
      <span class="lang-code">${active.label}</span>
      <span class="lang-caret">▼</span>`;

    // Build dropdown panel
    const dropdown = document.createElement('div');
    dropdown.className = 'lang-dropdown';
    dropdown.setAttribute('role', 'listbox');

    LANGS.forEach(({ code, label, flag, name }) => {
      const btn = document.createElement('button');
      btn.className = 'lang-btn' + (code === currentLang ? ' active' : '');
      btn.dataset.lang = code;
      btn.setAttribute('role', 'option');
      btn.setAttribute('aria-label', name);
      btn.innerHTML = `<span class="lang-flag">${flag}</span><span class="lang-code">${label}</span><span class="lang-name">${name}</span>`;
      btn.addEventListener('click', (e) => {
        e.stopPropagation();
        applyLang(code);
      });
      dropdown.appendChild(btn);
    });

    container.innerHTML = '';
    container.appendChild(trigger);
    container.appendChild(dropdown);

    // Toggle open/close on trigger
    trigger.addEventListener('click', (e) => {
      e.stopPropagation();
      container.classList.toggle('open');
    });
  });

  // Close on outside click
  document.addEventListener('click', () => {
    document.querySelectorAll('.lang-switcher.open').forEach(sw => sw.classList.remove('open'));
  });

  // Close on Escape
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') {
      document.querySelectorAll('.lang-switcher.open').forEach(sw => sw.classList.remove('open'));
    }
  });
}

document.addEventListener('DOMContentLoaded', () => {
  buildLangSwitcher();
  applyLang(getLang());
});
